from logs.logger import logger
from utils.conectar_banco_oracle import obter_conexao, liberar_conexao

def criar_banco():
    logger.info("Conectando ao Oracle...")

    try:
        conn = obter_conexao()
        cursor = conn.cursor()
        logger.info("Conexão estabelecida com sucesso.")

        logger.info("Criando tabela lote...")
        cursor.execute("""
            BEGIN
                EXECUTE IMMEDIATE '
                    CREATE TABLE lote (
                        id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        order_id NUMBER,
                        cliente VARCHAR2(150),
                        cpf_cnpj VARCHAR2(18),
                        email VARCHAR2(150),
                        cep VARCHAR2(9),
                        endereco VARCHAR2(255),
                        cidade VARCHAR2(100),
                        estado CHAR(2),
                        sku VARCHAR2(50),
                        produto VARCHAR2(255),
                        quantidade NUMBER,
                        valor_unitario NUMBER(15,2),
                        desconto NUMBER(15,2),
                        frete NUMBER(15,2),
                        valor_total NUMBER(15,2),
                        forma_pagamento VARCHAR2(50),
                        status VARCHAR2(50),
                        status_processamento VARCHAR2(50) DEFAULT ''PENDENTE'' NOT NULL,
                        batch VARCHAR2(50)
                    )
                ';
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE = -955 THEN
                        NULL; -- tabela já existe
                    ELSE
                        RAISE;
                    END IF;
            END;
        """)
        conn.commit()
        logger.info("Tabela lote criada com sucesso.")

    except Exception as e:
        logger.error("Erro ao criar tabela: %s", e)
    finally:
        cursor.close()
        liberar_conexao(conn)
        logger.info("Conexão encerrada.")

def main():
    criar_banco()

if __name__ == "__main__":
    main()
